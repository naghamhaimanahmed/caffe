const DICT: Record<Lang, Record<Key, string>> = { ar, en };
const STORAGE_KEY = "tf-lang";

export type Translate = (key: Key, params?: Record<string, string | number>) => string;

function makeI18n(lang: Lang, setLang: (l: Lang) => void) {
  const t: Translate = (key, params) => {
    const s = DICT[lang][key];
    return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
  };
  return {
    lang,
    setLang,
    dir: (lang === "ar" ? "rtl" : "ltr") as "rtl" | "ltr",
    isRtl: lang === "ar",
    /** Locale for Intl date formatting; digits stay Latin in both languages. */
    locale: lang === "ar" ? "ar-AE-u-nu-latn" : "en-GB",
    t,
    tr: (l: L) => l[lang],
    money: (n: number) => (lang === "ar" ? `${fmt(Math.round(n))} د.إ` : `AED ${fmt(Math.round(n))}`),
    currency: lang === "ar" ? "د.إ" : "AED",
  };
}

export type I18n = ReturnType<typeof makeI18n>;

const I18nContext = createContext<I18n | null>(null);

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      if (saved === "en" || saved === "ar") setLangState(saved);
    } catch {
      // storage unavailable: keep Arabic
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const value = useMemo(() => makeI18n(lang, setLang), [lang, setLang]);

  return (
    <I18nContext.Provider value={value}>
      <div dir={value.dir} lang={lang}>
        {children}
      </div>
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside <LangProvider>");
  return ctx;
}
